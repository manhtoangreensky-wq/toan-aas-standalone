def _clear_rate_limits() -> None:
    if hasattr(app_module, "_auth_rate_windows"):
        app_module._auth_rate_windows.clear()
    for mod_name in ("app",):
        m = sys.modules.get(mod_name)
        if m and hasattr(m, "_auth_rate_windows"):
            m._auth_rate_windows.clear()


