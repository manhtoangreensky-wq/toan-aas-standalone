    assert close2.status_code == 200
    assert close2.json()["ok"] is False
    assert close2.json()["error_code"] == "WEB_SUPPORT_CASE_CLOSED"

    # 6. Reliability Followup: acknowledge after resolved -> fails with OPS_RELIABILITY_FOLLOWUP_STATE_INVALID
