def _create_user(client: TestClient, session_db: Path, email: str, pwd: str, role: str = "customer") -> dict:
    _clear_rate_limits()
    reg = client.post("/api/v1/auth/register", json={"email": email, "password": pwd, "display_name": email.split("@")[0]})
    assert reg.status_code == 200

    with sqlite3.connect(str(session_db)) as conn:
        conn.execute("UPDATE web_accounts SET role_cache=? WHERE email=?", (role, email))
        row = conn.execute("SELECT id, role_cache FROM web_accounts WHERE email=?", (email,)).fetchone()
        conn.commit()

    _clear_rate_limits()
    login_resp = client.post("/api/v1/auth/login", json={"email": email, "password": pwd})
    assert login_resp.status_code == 200
    csrf = login_resp.json()["data"]["csrf_token"]
    cookies = dict(login_resp.cookies)

    authed_client = TestClient(app_module.app, cookies=cookies)
    authed_client.headers["X-CSRF-Token"] = csrf
    return {
        "client": authed_client,
        "account_id": str(row[0]),
        "role": str(row[1]),
        "csrf": csrf,
    }


